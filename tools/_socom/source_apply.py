_SHOWN = 12


def _shown(values: list[str]) -> str:
    head = ", ".join(values[:_SHOWN])
    return head + (f", +{len(values) - _SHOWN} more" if len(values) > _SHOWN else "")


def _sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _text(data: bytes) -> str:
    return data.decode("utf-8", "surrogateescape")


def _bytes(text: str) -> bytes:
    return text.encode("utf-8", "surrogateescape")


def _by_id(tracker: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {row["id"]: row for row in tracker.get("work_items", []) if isinstance(row, dict) and "id" in row}


# -- accepted plans ---------------------------------------------------------------


def cited_plan(root: Path, tracker: dict[str, Any], plan_item_id: str) -> tuple[dict[str, Any], str, str]:
    """(plan, repo-relative path, SHA-256) of an accepted plan item's owner plan.

    The plan lives at the packet's path; its current SHA-256 must be one the
    accepted item's evidence cites, so a plan edited after acceptance is
    refused as stale.
    """

    item = _by_id(tracker).get(plan_item_id)
    if item is None or item.get("kind") not in SOURCE_PLAN_KINDS:
        raise SocomError(f"{plan_item_id} is not a source-correlation plan item")
    if item.get("status") != "accepted":
        raise SocomError(f"{plan_item_id} is {item.get('status')}: only an accepted owner plan is applied")
    relative = plan_path(plan_item_id)
    path = root / relative
    if not path.is_file():
        raise SocomError(f"{relative} does not exist: the accepted owner plan of {plan_item_id} is gone")
    sha = sha256_file(path)
    cited = [
        text
        for text in list(item.get("evidence") or []) + list((item.get("handoff") or {}).get("evidence") or [])
        if isinstance(text, str)
    ]
    if not any(sha in text for text in cited):
        raise SocomError(
            f"stale plan: {relative} has SHA-256 {sha}, which the accepted {plan_item_id} does not cite; "
            "the plan changed after acceptance"
        )
    plan = load_json(path)
    if not isinstance(plan, dict) or plan.get("work_item_id") != plan_item_id:
        raise SocomError(f"{relative} is not the owner plan of {plan_item_id}")
    return plan, relative, sha


def reapply_amendments(tracker: dict[str, Any], apply_id: str) -> list[str]:
    """The open amendments that send ``apply_id`` back for re-apply (``progress amend-source-plan``)."""

    return sorted(str(row.get("id")) for row in open_source_amendments(tracker) if apply_id in (row.get("applies") or []))


def applied_state(tracker: dict[str, Any], plan_item_id: str, plan_sha256: str) -> dict[str, Any] | None:
    """The moves, creates and retired files every source apply recorded, or ``None``.

    A unit owned in several plans keeps one workspace file, so a plan may
    find its file already moved or created (or a shared retired file gone)
    by another plan's apply.  The plan's own record counts only when it
    names ``plan_sha256``, or while an open amendment sends its apply back
    for re-apply: the files it moved, created and retired stay applied, and
    the revised plan is checked against them.  ``source_plan.validate_source_plan``
    checks these paths in their applied state.
    """

    moves: list[dict[str, Any]] = []
    created: set[str] = set()
    retired: list[dict[str, Any]] = []
    found = False
    own = f"{plan_item_id}-apply"
    amended = bool(reapply_amendments(tracker, own))
    for item in tracker.get("work_items", []):
        record = item.get("source_apply")
        if item.get("kind") not in SOURCE_APPLY_KINDS or not isinstance(record, dict):
            continue
        if item.get("id") == own and record.get("plan_sha256") != plan_sha256 and not amended:
            continue
        found = True
        moves.extend(row for row in record.get("moves") or [] if isinstance(row, dict))
        created.update(str(path) for path in record.get("created") or [])
        retired.extend(row for row in record.get("retired") or [] if isinstance(row, dict))
    return {"moves": moves, "created": sorted(created), "retired": retired} if found else None


def content_sha256(data: bytes) -> str:
    """SHA-256 of a file without its generated blocks (its authored content)."""

    text = _text(data)
    try:
        bom, _blocks, rest = parse_blocks(text)
    except SocomError:
        return _sha256(data)
    return _sha256(_bytes(bom + rest))


def owner_map_sha256(plan: dict[str, Any]) -> str:
    """Digest of a plan's owner map: its scope, owner rows, header emits and unresolved rows."""

    body = {
        key: plan.get(key)
        for key in ("work_item_id", "scope", "graph_sha256", "slice_sha256", "owners", "header_emits", "unresolved")
    }
    return _sha256(canonical_json(body).encode("utf-8"))


def effective_reservation(apply: dict[str, Any], plan: dict[str, Any]) -> dict[str, Any]:
    """The directories an apply may write: its decomposed reservation or the plan's correction."""

    if apply.get("kind") == PROVIDER_APPLY_KIND:
        return {"directories": [], "status": "none", "reserved": []}
    reserved = sorted(decomposed_directories(apply), key=str.casefold)
    row = plan.get("reservation")
    if isinstance(row, dict) and row.get("status") == "corrected" and isinstance(row.get("directories"), list):
        return {"directories": sorted(row["directories"], key=str.casefold), "status": "corrected", "reserved": reserved}
    status = "confirmed" if isinstance(row, dict) and row.get("status") == "confirmed" else "reserved"
    return {"directories": reserved, "status": status, "reserved": reserved}


def _authored(plan: dict[str, Any]) -> list[dict[str, Any]]:
    return [
        owner
        for owner in plan.get("owners") or []
        if isinstance(owner, dict) and owner.get("classification") == "authored" and isinstance(owner.get("workspace_path"), str)
    ]


def provider_members(plan: dict[str, Any]) -> list[dict[str, Any]]:
    """The archive members a provider plan owns, one row per provider owner row."""

    rows = []
    for owner in plan.get("owners") or []:
        if not isinstance(owner, dict) or owner.get("classification") != "provider":
            continue
        member = owner.get("archive_member") or {}
        # Schema 2 entries may be objects: read them through artifact_ids.
        artifacts = artifact_ids(owner)
        row = {
            "library": owner.get("library"),
            "gnu_object": member.get("gnu_object"),
            "object": member.get("object"),
            "artifacts": len(artifacts),
            "artifacts_sha256": slice_sha256(artifacts),
        }
        # Schema 2: how the member was linked, its archive and version, when the plan records them.
        for key in ("linked", "archive", "version"):
            if member.get(key) is not None:
                row[key] = member[key]
        rows.append(row)
    return sorted(rows, key=lambda row: (str(row["library"]), str(row["gnu_object"] or ""), str(row["object"] or "")))


# -- generated docblocks ------------------------------------------------------------


def _assembly(path: str) -> bool:
    return path.casefold().endswith(".s")


def render_block(key: str, rows: list[dict[str, Any]], *, assembly: bool, newline: str = "\n") -> str:
    """One plan's generated docblock for one file."""

    body = [f"@socom-artifact {row['relation']} {row['section']} {row['artifact']}" for row in rows]
    if assembly:
        lines = [f"# {BLOCK_LABEL} begin {key}", f"# {GENERATED_NOTE}", *(f"# {line}" for line in body), f"# {BLOCK_LABEL} end {key}"]
    else:
        lines = [
            f"/* {BLOCK_LABEL} begin {key}",
            f" * {GENERATED_NOTE}",
            *(f" * {line}" for line in body),
            f" * {BLOCK_LABEL} end {key} */",
        ]
    return newline.join(lines) + newline


def parse_blocks(text: str) -> tuple[str, dict[str, str], str]:
    """(byte-order mark, generated blocks by plan item, the rest of the file).

    The blank line ``render_file`` puts after the leading blocks is not part
    of the rest.  A malformed block (unterminated, nested, mismatched or
    repeated) is refused.
    """

    bom = "﻿" if text.startswith("﻿") else ""
    lines = text[len(bom) :].splitlines(keepends=True)
    blocks: dict[str, str] = {}
    rest: list[str] = []
    leading = True
    index = 0
    while index < len(lines):
        begin = _BEGIN.match(lines[index].rstrip("\r\n"))
        if not begin:
            leading = False
            rest.append(lines[index])
            index += 1
            continue
        key = begin.group(1)
        end = index + 1
        while end < len(lines) and not _END.match(lines[end].rstrip("\r\n")):
            if _BEGIN.match(lines[end].rstrip("\r\n")):
                raise SocomError(f"generated block {key} is not terminated before another block begins")
            end += 1
        if end == len(lines):
            raise SocomError(f"generated block {key} is not terminated")
        closing = _END.match(lines[end].rstrip("\r\n"))
        assert closing is not None
        if closing.group(1) != key:
            raise SocomError(f"generated block {key} ends as {closing.group(1)}")
        if key in blocks:
            raise SocomError(f"generated block {key} appears twice")
        blocks[key] = "".join(lines[index : end + 1])
        index = end + 1
        if leading and index < len(lines) and not _BEGIN.match(lines[index].rstrip("\r\n")):
            leading = False
            if not lines[index].strip():
                index += 1  # the separator after the leading blocks
    return bom, blocks, "".join(rest)


def render_file(
    text: str | None, desired: dict[str, list[dict[str, Any]]], managed: set[str], *, assembly: bool
) -> str:
    """The file with the ``managed`` plans' blocks replaced by ``desired``.

    Other plans' blocks are kept.  Every block goes to the top of the file in
    plan-ID order, followed by one blank line and the rest of the file.
    """

    bom, blocks, rest = parse_blocks(text) if text is not None else ("", {}, "")
    newline = "\r\n" if text is not None and "\r\n" in text else "\n"
    for key in managed:
        blocks.pop(key, None)
    for key, rows in desired.items():
        blocks[key] = render_block(key, rows, assembly=assembly, newline=newline)
    head = "".join(blocks[key] for key in sorted(blocks))
    if head and rest:
        return bom + head + newline + rest
    return bom + head + rest


# -- pending file changes -------------------------------------------------------------


class Overlay:
    """Pending changes over the workspace: repo-relative path -> new bytes, or ``None`` (deleted)."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self.changes: dict[str, bytes | None] = {}

    def disk(self, relative: str) -> bytes | None:
        path = self.root / relative
        return path.read_bytes() if path.is_file() else None

    def read(self, relative: str) -> bytes | None:
        if relative in self.changes:
            return self.changes[relative]
        return self.disk(relative)

    def write(self, relative: str, data: bytes) -> None:
        self.changes[relative] = data

    def delete(self, relative: str) -> None:
        self.changes[relative] = None

    def move(self, source: str, target: str) -> None:
        data = self.read(source)
        if data is None:
            raise SocomError(f"cannot move {source}: it does not exist")
        self.write(target, data)
        self.delete(source)

    def changed(self) -> list[str]:
        """Paths whose pending content differs from the disk."""

        return sorted(path for path, data in self.changes.items() if data != self.disk(path))

    def commit(self) -> dict[str, bytes | None]:
        """Write every change; on failure restore the disk and re-raise.  Returns the backups."""

        paths = self.changed()
        backups = {path: self.disk(path) for path in paths}
        created_directories: list[Path] = []
        try:
            for path in paths:
                data = self.changes[path]
                if data is None:
                    continue
                parent = (self.root / path).parent
                missing = []
                while not parent.exists():
                    missing.append(parent)
                    parent = parent.parent
                created_directories.extend(reversed(missing))
                atomic_write_bytes(self.root / path, data)
            for path in paths:
                if self.changes[path] is None and (self.root / path).exists():
                    (self.root / path).unlink()
        except BaseException:
            self.rollback(backups, created_directories)
            raise
        self._created_directories = created_directories
        return backups

    def rollback(self, backups: dict[str, bytes | None], created_directories: list[Path] | None = None) -> None:
        for path, data in backups.items():
            target = self.root / path
            if data is None:
                if target.exists():
                    target.unlink()
            else:
                atomic_write_bytes(target, data)
        for directory in reversed(created_directories if created_directories is not None else getattr(self, "_created_directories", [])):
            try:
                directory.rmdir()
            except OSError:
                pass


# -- annotation targets ------------------------------------------------------------------


def annotation_changes(
    root: Path,
    tracker: dict[str, Any],
    plan_item: dict[str, Any],
    plan: dict[str, Any],
    directories: list[str],
    overlay: Overlay,
) -> dict[str, Any]:
    """The generated blocks a plan implies and the files whose blocks differ.

    Targets are every file the plan's annotations name, and every authored
    file the plan creates (it holds the plan's block, empty when it defines
    no named artifact).  A segment's own files (its authored workspace files
    and annotated files) also get the blocks of the accepted data
    reconciles' annotations into them.  A block of the plan in any other
    file is stale and removed.  Every target lies in ``directories``, or it
    is a problem.
    """

    plan_id = plan_item["id"]
    targets: dict[str, dict[str, list[dict[str, Any]]]] = {}
    for owner in _authored(plan):
        if owner.get("provisional_file") is None:
            # A file the plan creates holds its block even when it is empty.
            targets.setdefault(owner["workspace_path"], {}).setdefault(plan_id, [])
    for row in plan.get("annotations") or []:
        targets.setdefault(str(row["path"]), {}).setdefault(plan_id, []).append(row)
    managed = {plan_id}
    reconciles: list[str] = []
    pending: list[str] = []
    if plan_item.get("kind") == SEGMENT_PLAN_KIND:
        own = set(targets) | {owner["workspace_path"] for owner in _authored(plan)}
        for item in tracker.get("work_items", []):
            if item.get("kind") != DATA_RECONCILE_KIND or item.get("stage") != SOURCE_STAGE:
                continue
            if item.get("status") != "accepted":
                pending.append(item["id"])
                continue
            reconcile, _relative, _sha = cited_plan(root, tracker, item["id"])
            managed.add(item["id"])
            rows = [row for row in reconcile.get("annotations") or [] if str(row.get("path")) in own]
            for row in rows:
                targets.setdefault(str(row["path"]), {}).setdefault(item["id"], []).append(row)
            if rows:
                reconciles.append(item["id"])
    problems: list[str] = []
    outside = sorted(path for path in targets if not within(path, directories))
    if outside:
        problems.append(
            f"{len(outside)} annotated files lie outside the reservation ({', '.join(directories) or 'none'}): {_shown(outside)}"
        )
    changes: dict[str, str] = {}
    drift: list[dict[str, Any]] = []
    created: list[str] = []
    for path in sorted(targets):
        existing = overlay.read(path)
        text = None if existing is None else _text(existing)
        if text is None:
            created.append(path)
        try:
            rendered = render_file(text, targets[path], managed, assembly=_assembly(path))
        except SocomError as failure:
            problems.append(f"{path}: {failure}")
            continue
        if rendered != text:
            changes[path] = rendered
            drift.append({"path": path, "state": "missing-file" if text is None else "differs"})
    marker = f"{BLOCK_LABEL} begin {plan_id}"
    candidates = {path.relative_to(root).as_posix() for path in annotation_files(root)}
    candidates |= {path for path, data in overlay.changes.items() if data is not None}
    for path in sorted(candidates - set(targets)):
        data = overlay.read(path)
        if data is None:
            continue
        text = _text(data)
        if marker not in text:
            continue
        try:
            _bom, blocks, _rest = parse_blocks(text)
        except SocomError as failure:
            problems.append(f"{path}: {failure}")
            continue
        if plan_id not in blocks:
            continue
        changes[path] = render_file(text, {}, {plan_id}, assembly=_assembly(path))
        drift.append({"path": path, "state": "stale-block"})
        if not within(path, directories):
            problems.append(f"{path} holds a stale block of {plan_id} outside the reservation")
    count = sum(len(rows) for blocks in targets.values() for rows in blocks.values())
    digest = _sha256(
        canonical_json(
            [[path, key, rows] for path in sorted(targets) for key, rows in sorted(targets[path].items())]
        ).encode("utf-8")
    )
    return {
        "targets": targets,
        "changes": changes,
        "drift": drift,
        "created": created,
        "problems": problems,
        "reconciles": reconciles,
        "pending_reconciles": pending,
        "annotation_count": count,
        "annotations_sha256": digest,
    }


def _pending_moves(plan: dict[str, Any], overlay: Overlay) -> list[str]:
    return [
        f"{owner['provisional_file']} -> {owner['workspace_path']}"
        for owner in _authored(plan)
        if isinstance(owner.get("provisional_file"), str)
        and owner["provisional_file"] != owner["workspace_path"]
        and overlay.read(owner["provisional_file"]) is not None
        and overlay.read(owner["workspace_path"]) is None
    ]


def _pending_retires(plan: dict[str, Any], overlay: Overlay) -> list[str]:
    return [
        str(row["path"])
        for row in plan.get("retire_files") or []
        if isinstance(row, dict) and isinstance(row.get("path"), str) and overlay.read(row["path"]) is not None
    ]


def _apply_item(tracker: dict[str, Any], plan_item_id: str) -> dict[str, Any]:
    apply = _by_id(tracker).get(f"{plan_item_id}-apply")
    if apply is None or apply.get("kind") not in SOURCE_APPLY_KINDS:
        raise SocomError(f"{plan_item_id} has no source apply item")
    return apply


def require_lease(item: dict[str, Any], owner: str) -> None:
    lease = item.get("lease")
    if item.get("status") != "in_progress" or not isinstance(lease, dict):
        raise SocomError(f"{item['id']} is not actively leased")
    if lease.get("owner") != owner:
        raise SocomError(f"{item['id']} is leased by {lease.get('owner')}")


def annotate(root: Path, tracker: dict[str, Any], plan_item_id: str, *, write: bool, owner: str | None = None) -> dict[str, Any]:
    """``source annotate``: check (or write) an accepted plan's generated docblocks."""

    item = _by_id(tracker).get(plan_item_id)
    if item is None or item.get("kind") not in SOURCE_PLAN_KINDS:
        raise SocomError(f"{plan_item_id} is not a source-correlation plan item")
    if item.get("kind") == DATA_RECONCILE_KIND:
        raise SocomError(
            f"{plan_item_id} is a data reconcile: its annotations are written by the segment applies of its units' files"
        )
    plan, relative, sha = cited_plan(root, tracker, plan_item_id)
    apply = _apply_item(tracker, plan_item_id)
    if write:
        if not owner:
            raise SocomError("--write needs --owner, the lease owner of the plan's apply item")
        require_lease(apply, owner)
    reservation = effective_reservation(apply, plan)
    overlay = Overlay(root)
    result = annotation_changes(root, tracker, item, plan, reservation["directories"], overlay)
    problems = list(result["problems"])
    if item.get("kind") == PROVIDER_PLAN_KIND and result["targets"]:
        problems.append(f"{plan_item_id} is a provider plan: its apply writes no file, but the plan implies annotations")
    moves = _pending_moves(plan, overlay)
    retires = _pending_retires(plan, overlay)
    drift = list(result["drift"])
    drift.extend({"path": value, "state": "pending-move"} for value in moves)
    drift.extend({"path": value, "state": "pending-retire"} for value in retires)
    if write and moves:
        problems.append(f"moves are pending ({_shown(moves)}): progress apply-source-plan moves files before it annotates")
    if write and reservation["status"] == "corrected" and sorted(apply.get("resources") or [], key=str.casefold) != reservation["directories"]:
        problems.append(
            "the plan corrects the reservation: progress apply-source-plan re-reserves the corrected directories before "
            "anything is written"
        )
    written: list[str] = []
    if write and not problems and result["changes"]:
        for path, text in result["changes"].items():
            overlay.write(path, _bytes(text))
        written = overlay.changed()
        overlay.commit()
    return {
        "ok": not problems and (write or not drift),
        "mutation_performed": bool(written),
        "plan_item": plan_item_id,
        "plan": relative,
        "plan_sha256": sha,
        "reservation": reservation,
        "files": sorted(result["targets"]),
        "annotation_count": result["annotation_count"],
        "annotations_sha256": result["annotations_sha256"],
        "reconciles": result["reconciles"],
        "pending_reconciles": result["pending_reconciles"],
        "drift": drift,
        "written": written,
        "problems": problems,
    }


# -- the apply route ----------------------------------------------------------------------


def _record_lines(record: dict[str, Any]) -> list[str]:
    lines = [
        f"source-plan {record['plan']} sha256:{record['plan_sha256']}",
        f"source-owner-map-sha256:{record['owner_map_sha256']}",
        f"source-annotations-sha256:{record['annotations_sha256']} count:{record['annotation_count']}",
    ]
    if record.get("reservation", {}).get("status") != "none":
        reservation = record["reservation"]
        lines.append(f"source-reservation {reservation['status']} {', '.join(reservation['directories'])}")
    if record.get("amendments"):
        lines.append(f"source-reapply {' '.join(record['amendments'])}")
    lines.extend(f"source-file {row['path']} sha256:{row['sha256']}" for row in record["files"])
    lines.extend(f"source-moved {row['from']} -> {row['to']}" for row in record["moves"])
    lines.extend(f"source-created {path}" for path in record["created"])
    lines.extend(f"source-retired {row['path']} sha256:{row['sha256']} bytes:{row['bytes']}" for row in record["retired"])
    lines.extend(
        f"source-provider-member {row['library']} gnu_object:{row['gnu_object'] or '-'} object:{row['object'] or '-'} "
        f"artifacts:{row['artifacts']}"
        + "".join(f" {key}:{row[key]}" for key in ("archive", "version", "linked") if row.get(key) is not None)
        for row in record.get("members") or []
    )
    return lines


def prepare_apply(
    root: Path,
    tracker: dict[str, Any],
    item_id: str,
    owner: str,
    graph: dict[str, Any],
    section_of: Callable[[int], str | None],
) -> tuple[dict[str, Any], Overlay]:
    """The ``source_apply`` record and pending file changes of one apply; refuses what it may not do."""

    item = _by_id(tracker).get(item_id)
    if item is None or item.get("kind") not in SOURCE_APPLY_KINDS:
        raise SocomError(f"{item_id} is not a source apply item")
    require_lease(item, owner)
    plan_item_id = item_id.removesuffix("-apply")
    plan_item = _by_id(tracker)[plan_item_id]
    plan, relative, sha = cited_plan(root, tracker, plan_item_id)
    previous = item.get("source_apply") if isinstance(item.get("source_apply"), dict) else None
    # A re-apply for an open amendment starts from the files the previous apply left.
    amendments = reapply_amendments(tracker, item_id)
    applied = previous if previous and (previous.get("plan_sha256") == sha or amendments) else None
    merged = applied_state(tracker, plan_item_id, sha)
    report = validate_source_plan(root, tracker, plan, graph, section_of=section_of, applied=merged)
    if not report["ok"]:
        raise SocomError(
            f"{relative} no longer validates against the workspace ({len(report['problems'])} problems): "
            + "; ".join(report["problems"][:_SHOWN])
        )
    reservation = effective_reservation(item, plan)
    overlay = Overlay(root)
    record: dict[str, Any] = {
        "kind": SOURCE_APPLY_RECORD_KIND,
        "schema_version": SOURCE_APPLY_RECORD_SCHEMA,
        "plan_item": plan_item_id,
        "plan": relative,
        "plan_sha256": sha,
        "owner_map_sha256": owner_map_sha256(plan),
        "scope": plan.get("scope"),
        "reservation": reservation,
        "moves": [],
        "created": [],
        "retired": [],
        "removed": [],
        "files": [],
        "reconciles": [],
        "applied_by": owner,
    }
    if amendments:
        record["amendments"] = amendments
    if item["kind"] == PROVIDER_APPLY_KIND:
        writes = [
            name
            for name, present in (
                ("authored owner rows", bool(_authored(plan))),
                ("header emits", bool(plan.get("header_emits"))),
                ("annotations", bool(plan.get("annotations"))),
                ("retire_files", bool(plan.get("retire_files"))),
            )
            if present
        ]
        if writes:
            raise SocomError(f"{item_id} writes no file under src/, but its plan has {', '.join(writes)}")
        record.update(members=provider_members(plan), annotation_count=0)
        record["annotations_sha256"] = _sha256(canonical_json([]).encode("utf-8"))
        record["changed"] = []
        return record, overlay

    # This apply's own earlier run (a rerun is idempotent), and what any
    # apply did (a unit file shared with another plan may already be moved,
    # created or retired by that plan's apply, which records it).
    done = applied or {}
    done_moves = {(row.get("from"), row.get("to")) for row in done.get("moves") or []}
    done_created = set(done.get("created") or [])
    done_retired = {row.get("path"): row for row in done.get("retired") or []}
    other = merged or {}
    other_moves = {(row.get("from"), row.get("to")) for row in other.get("moves") or []}
    other_retired = {row.get("path") for row in other.get("retired") or []}
    for row in _authored(plan):
        workspace, provisional = row["workspace_path"], row.get("provisional_file")
        if isinstance(provisional, str) and provisional != workspace:
            if overlay.read(provisional) is not None and overlay.read(workspace) is None:
                overlay.move(provisional, workspace)
                record["moves"].append({"from": provisional, "to": workspace})
            elif (provisional, workspace) in done_moves:
                record["moves"].append({"from": provisional, "to": workspace})
            elif (provisional, workspace) not in other_moves:
                raise SocomError(f"cannot move {provisional} to {workspace}: the source is missing or the target exists")
        elif provisional is None and (overlay.read(workspace) is None or workspace in done_created):
            record["created"].append(workspace)
    for row in plan.get("retire_files") or []:
        path = row["path"]
        data = overlay.read(path)
        if data is not None:
            record["retired"].append({"path": path, "sha256": _sha256(data), "bytes": len(data)})
            overlay.delete(path)
        elif path in done_retired:
            record["retired"].append({key: done_retired[path][key] for key in ("path", "sha256", "bytes")})
        elif path not in other_retired:
            raise SocomError(f"cannot retire {path}: it does not exist")
    result = annotation_changes(root, tracker, plan_item, plan, reservation["directories"], overlay)
    if result["pending_reconciles"]:
        raise SocomError(f"data reconciles are not accepted yet: {_shown(result['pending_reconciles'])}")
    if result["problems"]:
        raise SocomError("; ".join(result["problems"]))
    for path, text in result["changes"].items():
        overlay.write(path, _bytes(text))
    moved_to = {row["to"] for row in record["moves"]}
    for path in sorted(set(result["created"]) | (done_created & set(result["targets"]))):
        if path not in record["created"] and path not in moved_to:
            record["created"].append(path)
    managed = sorted(set(result["targets"]) | {row["to"] for row in record["moves"]})
    removed = sorted({row["from"] for row in record["moves"]} | {row["path"] for row in record["retired"]})
    touched = sorted(set(managed) | set(removed) | set(overlay.changes))
    outside = [path for path in touched if not within(path, reservation["directories"])]
    if outside:
        raise SocomError(
            f"refused: {len(outside)} paths lie outside the reservation of {item_id} "
            f"({', '.join(reservation['directories'])}): {_shown(outside)}"
        )
    files = []
    for path in managed:
        data = overlay.read(path)
        if data is None:
            raise SocomError(f"{path} would not exist after the apply")
        files.append({"path": path, "sha256": _sha256(data), "content_sha256": content_sha256(data)})
    record.update(
        created=sorted(record["created"]),
        moves=sorted(record["moves"], key=lambda row: (row["from"], row["to"])),
        retired=sorted(record["retired"], key=lambda row: row["path"]),
        removed=removed,
        files=files,
        reconciles=result["reconciles"],
        annotation_count=result["annotation_count"],
        annotations_sha256=result["annotations_sha256"],
        changed=overlay.changed(),
    )
    return record, overlay


def record_apply(item: dict[str, Any], record: dict[str, Any], applied_at: str) -> None:
    """Store an apply's record and evidence lines on its item; re-reserve a corrected reservation."""

    record = dict(record, applied_at=applied_at)
    previous = item.get("source_apply")
    if (
        record.get("amendments")
        and isinstance(previous, dict)
        and sorted(previous.get("amendments") or []) != record["amendments"]
    ):
        # The first re-apply for an open amendment replaces the record; the history keeps it.
        item.setdefault("review_history", []).append(
            {"amendments": list(record["amendments"]), "replaced_at": applied_at, "source_apply": copy.deepcopy(previous)}
        )
    item["source_apply"] = record
    kept = [text for text in item.get("evidence") or [] if not str(text).startswith(APPLY_EVIDENCE_PREFIXES)]
    item["evidence"] = sorted(set(kept) | set(_record_lines(record)))
    reservation = record["reservation"]
    if item.get("kind") == SEGMENT_APPLY_KIND and reservation["status"] == "corrected":
        batch = item.setdefault("batch", {})
        if not isinstance(batch.get("reservation_correction"), dict):
            batch["reservation_correction"] = {"from": list(item.get("resources") or [])}
        batch["reservation_correction"]["plan_sha256"] = record["plan_sha256"]
        item["resources"] = list(reservation["directories"])
        batch["directories"] = list(reservation["directories"])


def verify_source_apply(root: Path, tracker: dict[str, Any], item: dict[str, Any]) -> list[str]:
    """``source apply-check``: an applied item still matches its accepted plan and record."""

    problems: list[str] = []
    record = item.get("source_apply")
    if item.get("kind") not in SOURCE_APPLY_KINDS:
        return [f"{item.get('id')} is not a source apply item"]
    if not isinstance(record, dict):
        return [f"{item['id']} has no source_apply record: run progress apply-source-plan first"]
    plan_item_id = str(item["id"]).removesuffix("-apply")
    try:
        plan, relative, sha = cited_plan(root, tracker, plan_item_id)
    except SocomError as failure:
        return [str(failure)]
    if record.get("plan_sha256") != sha or record.get("plan") != relative:
        problems.append(f"the record applied plan {record.get('plan_sha256')}, the accepted plan is {sha}")
    if record.get("owner_map_sha256") != owner_map_sha256(plan):
        problems.append("the record's owner-map digest differs from the accepted plan's")
    for row in record.get("files") or []:
        path = root / str(row.get("path"))
        if not path.is_file():
            problems.append(f"{row.get('path')} is missing")
            continue
        data = path.read_bytes()
        # Another plan's apply may add its own generated block to a shared
        # unit file: the authored content must still be the applied one.
        if _sha256(data) != row.get("sha256") and content_sha256(data) != row.get("content_sha256"):
            problems.append(f"{row.get('path')} changed after the apply")
    for path in record.get("removed") or []:
        if (root / str(path)).exists():
            problems.append(f"{path} was removed by the apply but exists")
    if item["kind"] == PROVIDER_APPLY_KIND:
        if record.get("files") or record.get("removed"):
            problems.append(f"{item['id']} is a provider apply: it records files")
        if record.get("members") != provider_members(plan):
            problems.append("the recorded archive members differ from the plan's provider rows")
        return problems
    directories = sorted(item.get("resources") or [], key=str.casefold)
    if (record.get("reservation") or {}).get("directories") != directories:
        problems.append(f"the record's reservation differs from {item['id']}'s resources {directories}")
    paths = [str(row.get("path")) for row in record.get("files") or []] + [str(path) for path in record.get("removed") or []]
    outside = [path for path in paths if not within(path, directories)]
    if outside:
        problems.append(f"recorded paths lie outside the reservation: {_shown(outside)}")
    plan_item = _by_id(tracker)[plan_item_id]
    try:
        result = annotation_changes(root, tracker, plan_item, plan, directories, Overlay(root))
    except SocomError as failure:
        problems.append(str(failure))
    else:
        problems.extend(result["problems"])
        if result["drift"]:
            problems.append(
                "generated annotations drifted: " + _shown([f"{row['path']} ({row['state']})" for row in result["drift"]])
            )
    return problems


# -- completeness under the lean model ---------------------------------------------------------


def lean_completeness(root: Path, tracker: dict[str, Any], parsed: dict[str, Any]) -> dict[str, Any]:
    """Stage 4 completeness against accepted owner plans and their generated annotations.

    Every planning scope's owner plan must be accepted and unchanged, and
    every segment and provider apply accepted with a record of that plan.
    Every artifact of a scope is owned by an owner row of its plan (an
    unresolved row is incomplete).  Every annotation an accepted plan
    implies (one ``defines`` per named artifact of an authored row, one
    ``emits`` per header emit) must be in the source exactly once, and the
    source may hold no other ``@socom-artifact`` line.  Compiler-generated
    artifacts, provider members and unnamed artifacts are covered by their
    owner rows' artifact lists.
    """

    errors: list[str] = []
    items = [row for row in tracker.get("work_items", []) if row.get("stage") == SOURCE_STAGE]
    by_id = {row["id"]: row for row in items}
    plans = [row for row in items if row.get("kind") in SOURCE_PLAN_KINDS]
    if not plans:
        errors.append(f"{SOURCE_STAGE} has no owner plans: completeness is checked against accepted owner plans")
    expected: set[tuple[str, str, str, str]] = set()
    owned = 0
    unresolved: list[str] = []
    not_accepted: list[str] = []
    unapplied: list[str] = []
    for item in plans:
        if item.get("status") != "accepted":
            not_accepted.append(item["id"])
            continue
        try:
            plan, relative, sha = cited_plan(root, tracker, item["id"])
        except SocomError as failure:
            errors.append(str(failure))
            continue
        artifacts = [
            identity
            for owner in plan.get("owners") or []
            if isinstance(owner, dict)
            for identity in owner.get("artifacts") or []
        ]
        rows = [row["artifact"] for row in plan.get("unresolved") or [] if isinstance(row, dict)]
        if len(artifacts) + len(rows) != (item.get("batch") or {}).get("artifact_count"):
            errors.append(f"{relative} lists {len(artifacts) + len(rows)} artifacts, its scope has {(item.get('batch') or {}).get('artifact_count')}")
        owned += len(artifacts)
        unresolved.extend(rows)
        for row in plan.get("annotations") or []:
            expected.add((str(row["relation"]), str(row["section"]), str(row["artifact"]), str(row["path"])))
        if item.get("kind") != DATA_RECONCILE_KIND:
            apply = by_id.get(f"{item['id']}-apply") or {}
            if apply.get("status") != "accepted" or (apply.get("source_apply") or {}).get("plan_sha256") != sha:
                unapplied.append(f"{item['id']}-apply")
    if not_accepted:
        errors.append(f"{len(not_accepted)} owner plans are not accepted: {_shown(not_accepted)}")
    if unapplied:
        errors.append(f"{len(unapplied)} source applies are not accepted with a record of their accepted plan: {_shown(unapplied)}")
    if unresolved:
        errors.append(f"{len(unresolved)} artifacts are unresolved in accepted owner plans: {_shown(unresolved)}")
    actual = {(row["relation"], row["section"], row["artifact_id"], row["path"]) for row in parsed.get("artifacts", [])}
    missing = sorted(expected - actual, key=lambda row: (row[3], row[2], row[0]))
    extra = sorted(actual - expected, key=lambda row: (row[3], row[2], row[0]))
    if missing:
        errors.append(
            f"{len(missing)} annotations the accepted owner plans imply are missing from source: "
            + _shown([f"{row[0]} {row[2]} in {row[3]}" for row in missing])
        )
    if extra:
        errors.append(
            f"{len(extra)} source annotations no accepted owner plan implies: "
            + _shown([f"{row[0]} {row[2]} in {row[3]}" for row in extra])
        )
    return {
        "errors": errors,
        "plan_count": len(plans),
        "accepted_plan_count": len(plans) - len(not_accepted),
        "owned_artifact_count": owned,
        "expected_annotation_count": len(expected),
        "missing_artifact_ids": sorted({row[2] for row in missing} | set(unresolved)),
    }
