"""Stage 4 (source-correlation): generated owner annotations and the guarded apply route.

An accepted owner plan (``source_plan.py``) is applied under its apply
item's lease:

* a segment apply moves provisional files to their workspace paths, deletes
  the plan's ``retire_files`` and writes the plan's derived annotations (plus
  those the accepted data reconciles assign to the segment's files) as
  generated docblocks.  It may write only the directories its apply item
  reserves, or the plan's recorded ``reservation`` correction, which it
  reserves on the item first;
* a provider apply writes no file: it records each archive member's
  ownership (library and GNU object or object name) in tracker evidence.

Every apply records a ``source_apply`` record on its item: the plan file and
its SHA-256 (which the accepted plan item must cite), an owner-map digest,
the files it leaves written with their SHA-256s, the moves, creates and
retired files (path and content SHA-256; git history keeps the content), and
the reservation it wrote within.  The record's lines are copied into the
item's evidence.

Generated docblocks are deterministic and idempotent.  Each names the plan
item whose annotations it holds; a file may hold the blocks of several plans
(a unit's text segment, its static-initializer segment and a data
reconcile), kept in plan-ID order at the top of the file.  The begin and end
lines carry no ``@socom-`` token, so ``audit docblocks`` and ``audit
source-trace`` parse only the ``@socom-artifact`` lines between them::

    /* socom-owner-annotations begin socom:work:source-segment-001
     * Generated by source annotate from the accepted owner plan; do not edit.
     * @socom-artifact defines main socom:function:0x140000
     * socom-owner-annotations end socom:work:source-segment-001 */

Assembly files (``.s``) use ``#`` line comments instead.
"""

