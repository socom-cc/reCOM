SOURCE_APPLY_RECORD_KIND = "socom-source-apply"
SOURCE_APPLY_RECORD_SCHEMA = 1
BLOCK_LABEL = "socom-owner-annotations"
GENERATED_NOTE = "Generated by source annotate from the accepted owner plan; do not edit."
_BEGIN = re.compile(r"^\s*(?:/\*|#)\s*socom-owner-annotations\s+begin\s+(\S+)\s*$")
_END = re.compile(r"^\s*(?:\*|#)\s*socom-owner-annotations\s+end\s+(\S+?)\s*(?:\*/)?\s*$")
