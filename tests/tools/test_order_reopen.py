def _opened(live: dict, item: str = "socom:work:source-segment-022") -> tuple[dict, str]:
    tracker = copy.deepcopy(live)
    report = open_source_amendment(tracker, item, "socom-reviewer-r1", "a user placement moves functions", ["placements"])
    refresh_ready_and_stages(tracker)
    return tracker, report["amendment"]


def _items(tracker: dict) -> dict[str, dict]:
    return {row["id"]: row for row in tracker["work_items"]}


def test_a_reopen_selects_the_stage_5_items_built_on_the_amended_plan(live: dict) -> None:
    tracker, amendment = _opened(live)
    row = next(row for row in tracker["stages"] if row["name"] == "source-correlation")["amendments"][-1]
    chosen = select_items(tracker, row, [])
    # Its own segment's order plan and apply, every skeleton item that wrote a file its stage 4 apply recorded
    # (headers mean the prepare), and the plan of each such apply.
    assert {"socom:work:order-segment-022", "socom:work:order-segment-022-apply"} <= set(chosen)
    for item_id in chosen:
        kind = _items(tracker)[item_id]["kind"]
        if kind == ORDER_APPLY_KIND:
            assert item_id.removesuffix("-apply") in chosen
    record = reopen_for_amendment(tracker, amendment, [], "socom-reopener-r2", "placement", ["user decision"], lambda _digest: True)
    refresh_ready_and_stages(tracker)
    tracker["revision"] += 1
    items = _items(tracker)
    assert record["kind"] == REOPENING_KIND and record["status"] == "open" and record["items"] == sorted(chosen)
    for item_id in record["items"]:
        item = items[item_id]
        # Held: blocked (the refresh does not make a plan ready) with a review-history entry; the record stays.
        assert item["status"] == "blocked" and item["review_history"][-1]["order_reopening"] == record["id"]
        assert item["review_history"][-1]["accepted"] and "accepted" not in item
        if item["kind"] == ORDER_APPLY_KIND:
            assert item["order_skeleton"] == item["review_history"][-1]["order_skeleton"]
    assert set(held_items(tracker)) == set(record["items"])
    assert audit_tracker(tracker) == []
    stage = next(row for row in tracker["stages"] if row["name"] == ORDER_STAGE)
    assert stage["reopenings"][-1]["amendment"] == amendment
    # The audit holds a reopened item blocked until a rebase absorbs the amendment.
    broken = copy.deepcopy(tracker)
    _items(broken)["socom:work:order-segment-022"]["status"] = "ready"
    assert any("holds it until a rebase" in text for text in audit_tracker(broken))

    # Stage 4's re-apply may rewrite the reopened items' files for this amendment, and no other skeleton file.
    own = items["socom:work:order-segment-022-apply"]["order_skeleton"]["files"][0]["path"]
    refuse_stage4_writes(tracker, [own], [amendment])
    other = next(row for row in tracker["work_items"] if row.get("kind") == ORDER_APPLY_KIND and row["id"] not in record["items"])
    written = next(entry["path"] for entry in other["order_skeleton"]["files"] if entry["before_sha256"] != entry["after_sha256"])
    with pytest.raises(SocomError, match="reopen-order-skeleton --amendment"):
        refuse_stage4_writes(tracker, [written], [amendment])
    # An item sent back otherwise (not for this amendment) is refused too; without an amendment, as before.
    other["status"] = "ready"
    with pytest.raises(SocomError, match="not reopened for"):
        refuse_stage4_writes(tracker, [written], [amendment])
    refuse_stage4_writes(tracker, [written])


def test_reopen_refusals(live: dict) -> None:
    tracker, amendment = _opened(live)
    accepted = next(row["id"] for row in next(row for row in tracker["stages"] if row["name"] == "source-correlation")["amendments"]
                    if row["status"] == "accepted")
    with pytest.raises(SocomError, match="not open"):
        reopen_for_amendment(tracker, accepted, [], "socom-reopener-r2", "r", ["e"], lambda _digest: True)
    with pytest.raises(SocomError, match="unknown stage 4 amendment"):
        reopen_for_amendment(tracker, "socom:source-amendment:999", [], "socom-reopener-r2", "r", ["e"], lambda _digest: True)
    for by, reason, evidence, match in (("", "r", ["e"], "--by"), ("w", " ", ["e"], "reason"), ("w", "r", [], "evidence")):
        with pytest.raises(SocomError, match=match):
            reopen_for_amendment(tracker, amendment, [], by, reason, evidence, lambda _digest: True)
    with pytest.raises(SocomError, match="is not a stage 5 order plan"):
        reopen_for_amendment(tracker, amendment, ["socom:work:order-segment-022-compile"], "w", "r", ["e"], lambda _digest: True)
    apply = _items(tracker)["socom:work:order-segment-022-apply"]
    owner = apply["handoff"]["owner"]
    with pytest.raises(SocomError, match="not reopened by its handoff owner"):
        reopen_for_amendment(tracker, amendment, [], owner, "r", ["e"], lambda _digest: True)
    with pytest.raises(SocomError, match="no merge ancestor is stored"):
        reopen_for_amendment(tracker, amendment, [], "w", "r", ["e"], lambda _digest: False)
    leased = copy.deepcopy(tracker)
    _items(leased)["socom:work:order-segment-022-apply"].update(status="in_progress", lease={"owner": "worker-x"})
    with pytest.raises(SocomError, match="leased by worker-x"):
        reopen_for_amendment(leased, amendment, [], "w", "r", ["e"], lambda _digest: True)
    review = copy.deepcopy(tracker)
    _items(review)["socom:work:order-segment-022"]["status"] = "awaiting_acceptance"
    with pytest.raises(SocomError, match="awaiting acceptance"):
        reopen_for_amendment(review, amendment, [], "w", "r", ["e"], lambda _digest: True)
    # A second amendment holds items another reopening sent back already: its stage 4 re-apply needs them too.
    first = reopen_for_amendment(tracker, amendment, [], "w", "r", ["e"], lambda _digest: True)
    second_tracker, second = tracker, open_source_amendment(tracker, "socom:work:source-segment-023", "socom-reviewer-r1", "r", ["e"])["amendment"]
    record = reopen_for_amendment(second_tracker, second, [], "w", "r", ["e"], lambda _digest: True)
    assert "socom:work:order-segment-023-apply" in record["items"] and set(record["already_held"]) <= set(first["items"])
    refresh_ready_and_stages(second_tracker)
    second_tracker["revision"] += 1
    assert audit_tracker(second_tracker) == []


