def _accept_order_plans(root: Path, capsys) -> None:
    for item, planner in (("socom:work:order-segment-001", "planner-1"), ("socom:work:order-segment-003", "planner-3"),
                          (ORDER_LINK_ID, "planner-link")):
        _claim(root, capsys, item, owner=planner)
        code, report = _run(capsys, "--root", str(root), "order", "plan", "draft", "--item", item)
        assert code == 0, report
        assert _handoff(root, capsys, item, planner, _cited(root, item))[0] == 0
        assert _accept(root, capsys, item)[0] == 0


def _stage5(root: Path) -> dict:
    return next(row for row in _load(root)["stages"] if row["name"] == ORDER_STAGE)


def test_stage_5_rebases_onto_the_baseline_of_accepted_amendments(amendable: tuple[Path, dict, str], capsys, monkeypatch) -> None:
    root, graph, gap = amendable
    assert _decompose(root, capsys)[0] == 0
    _accept_order_plans(root, capsys)
    decomposed = _stage5(root)["decomposition"]["stage4_baseline_sha256"]
    rebase = ["--root", str(root), "progress", "rebase-function-order", "--by", "socom-rebaser-r5", "--reason",
              "absorb the amendment", "--evidence", "accept-source-amendment recorded the baseline"]
    code, refused = _run(capsys, *rebase, "--expected-revision", _revision(root))
    assert code == 2 and "nothing to absorb" in refused["error"], refused

    # The amendment: the data reconcile gives the deferred gap an owner in segment 1.
    code, report = _amend(root, capsys, DATA)
    assert code == 0, report
    reopen = ["--root", str(root), "progress", "reopen-order-skeleton", "--amendment", FIRST, "--by", "socom-reopener-r4",
              "--reason", "the reconcile gives the gap an owner", "--evidence", "amendment 001 opened"]
    code, preview = _run(capsys, *reopen, "--expected-revision", _revision(root), "--dry-run")
    assert code == 0 and preview["errors"] == [] and preview["reopening"]["items"] == ["socom:work:order-segment-001",
                                                                                        "socom:work:order-segment-001-apply"], preview
    code, report = _run(capsys, *reopen, "--expected-revision", _revision(root))
    assert code == 0, report
    record = report["reopening"]
    assert record["sent_back"] == ["socom:work:order-segment-001"] and record["held_as"] == {"socom:work:order-segment-001-apply": "blocked"}
    assert report["statuses"] == {"socom:work:order-segment-001": "blocked", "socom:work:order-segment-001-apply": "blocked"}
    # Held: no re-draft or validation before the amendment is accepted and absorbed; the rebase refuses an open amendment.
    code, refused = _run(capsys, "--root", str(root), "order", "plan", "draft", "--item", "socom:work:order-segment-001")
    assert code == 2 and "held by the open reopening" in refused["error"], refused
    code, refused = _run(capsys, *rebase, "--expected-revision", _revision(root))
    assert code == 2 and "amendments are open" in refused["error"], refused

    plan = _plan(root, DATA)
    plan["owners"].append(_generated([gap]))
    plan["unresolved"] = []
    from tools._socom.source_plan import derive_annotations

    plan["annotations"] = derive_annotations(plan, graph, MAIN)
    _revise(root, capsys, DATA, plan)
    _reapply(root, capsys, f"{SEGMENT_1}-apply")
    _receipt(monkeypatch, _stage3_receipt(root))
    code, accepted = _accept_amendment(root, capsys)
    assert code == 0, accepted
    baseline = accepted["baseline_sha256"]
    # Accepted, not yet absorbed: the plan stays held, the reopen route is closed for the accepted amendment.
    assert _stage5(root)["reopenings"][0]["status"] == "open"
    code, refused = _run(capsys, *reopen, "--expected-revision", _revision(root))
    assert code == 2 and "not open" in refused["error"], refused

