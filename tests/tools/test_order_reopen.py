def _unit(*functions: tuple[str, str], block: str = BLOCK) -> bytes:
    """A skeleton unit file: the stage 4 block, an include, then one fenced entry per (mangled name, text)."""

    parts = [block, "\n", '#include "demo.h"\n']
    for name, text in functions:
        parts += ["\n", f"/* @socom-skeleton stub {name} */\n", text]
    return "".join(parts).encode()


OLD = _unit(("f__Fv", "void f()\n{\n}\n"), ("g__Fv", "void g()\n{\n}\n"))


def _setup(tmp_path: Path, ours: bytes, theirs: bytes, *, previous: bytes = OLD, blob: bool = True) -> tuple[dict, dict, dict, Path]:
    """A skeleton apply whose previous record rendered ``previous``; src/ holds ``ours``, the new render is ``theirs``."""

    base = tmp_path / "base"
    (base / PATH).parent.mkdir(parents=True, exist_ok=True)
    (base / PATH).write_bytes(_unit())
    (tmp_path / PATH).parent.mkdir(parents=True, exist_ok=True)
    (tmp_path / PATH).write_bytes(ours)
    row = {"path": PATH, "action": "unit", "before_sha256": sha(_unit()), "after_sha256": sha(previous)}
    item = {"id": APPLY, "kind": ORDER_APPLY_KIND, "status": "in_progress", "resources": [PATH],
            "order_skeleton": {"kind": "socom-order-skeleton-apply", "item": APPLY, "files": [row]}}
    if blob:
        put_blob(tmp_path, previous)
    rendered = {"files": {PATH: theirs}, "manifest": {"files": [{"path": PATH, "action": "unit"}], "deleted": []}}
    return {"work_items": [item]}, item, rendered, base


# -- the merge -------------------------------------------------------------------------------


def test_equal_sides_decide_without_a_merge_and_absent_files_conflict() -> None:
    old, edited, new = b"a\nb\n", b"a\nB\n", b"a\nb\nc\n"
    assert merge_file(sha(old), old, edited, old).kind == "kept"  # the render did not change: the later edit stays
    rendered = merge_file(sha(old), old, old, new)
    assert (rendered.kind, rendered.data, rendered.write) == ("render", new, True)
    assert merge_file(sha(old), old, new, new).kind == "same"
    # Only the digest is known: the decisions by digest still hold, a real merge refuses.
    assert merge_file(sha(old), None, edited, old).kind == "kept"
    with pytest.raises(SocomError, match="not stored"):
        merge_file(sha(old), None, edited, new)
    # The render deletes a file that was edited since: a conflict, never a silent loss.
    deleted = merge_file(sha(old), old, edited, None)
    assert deleted.kind == "conflict" and deleted.conflicts == [{"presence": {"ancestor": True, "ours": True, "theirs": False}}]
    # CRLF checkouts merge on LF text and keep their own style; adjacent changes conflict (classic merge3).
    lines = b"a\nb\nc\nd\n"
    crlf = merge_file(sha(lines), lines, b"A\r\nb\r\nc\r\nd\r\n", lines + b"e\n")
    assert crlf.kind == "clean" and crlf.data == b"A\r\nb\r\nc\r\nd\r\ne\r\n"
    assert merge_file(sha(old), old, edited, new).kind == "conflict"


def test_a_clean_merge_keeps_a_later_edit_and_applies_the_new_render(tmp_path: Path) -> None:
    edited = OLD.replace(b"void f()\n{\n}\n", b"void f()\n{\n\tport_init();\n}\n")
    new = _unit(("f__Fv", "void f()\n{\n}\n"), ("g__Fv", "void g()\n{\n}\n"), ("h__Fv", "void h()\n{\n}\n"))
    tracker, item, rendered, base = _setup(tmp_path, edited, new, blob=False)
    # The previous render is neither stored nor what the new inputs render: the merge refuses, nothing is written.
    with pytest.raises(SocomError, match="progress reopen-order-skeleton"):
        _merge_scope(tmp_path, tracker, item, rendered, base, None)
    put_blob(tmp_path, OLD)
    rows, changes, blobs = _merge_scope(tmp_path, tracker, item, rendered, base, None)
    merged = changes[PATH]
    assert b"\tport_init();" in merged and b"/* @socom-skeleton stub h__Fv */\nvoid h()" in merged
    (row,) = rows
    assert row["merge"] == "clean" and row["ancestor_sha256"] == sha(OLD) and row["rendered_sha256"] == sha(new)
    assert (row["before_sha256"], row["after_sha256"], row["base_sha256"]) == (sha(edited), sha(merged), sha(_unit()))
    assert check_merged(PATH, merged, new) == [] and sha(OLD) in {sha(data) for data in blobs}
    # Unchanged inputs (theirs is the previous render) keep src/ as it is: no write.
    tracker, item, rendered, base = _setup(tmp_path, edited, OLD)
    rows, changes, _blobs = _merge_scope(tmp_path, tracker, item, rendered, base, None)
    assert changes == {} and rows[0]["merge"] == "kept" and rows[0]["after_sha256"] == sha(edited)


def test_a_conflicting_edit_writes_nothing_and_reports_the_hunks_until_a_resolution_is_given(tmp_path: Path) -> None:
    edited = OLD.replace(b"void g()\n", b"void g() /* port: real body */\n")
    new = OLD.replace(b"void g()\n", b"void g(int)\n")
    tracker, item, rendered, base = _setup(tmp_path, edited, new)
    with pytest.raises(SocomError, match="nothing written: 1 files conflict") as failure:
        _merge_scope(tmp_path, tracker, item, rendered, base, None)
    assert conflict_report_path(APPLY) in str(failure.value)
    report = json.loads((tmp_path / conflict_report_path(APPLY)).read_text(encoding="utf-8"))
    (row,) = report["files"]
    assert (row["path"], row["ours_sha256"], row["theirs_sha256"]) == (PATH, sha(edited), sha(new))
    (hunk,) = row["hunks"]
    assert hunk["ours"] == "void g() /* port: real body */\n" and hunk["theirs"] == "void g(int)\n" and hunk["ancestor"] == "void g()\n"
    assert hunk["ours_lines"] == hunk["theirs_lines"] == hunk["ancestor_lines"]
    marked = (tmp_path / conflict_marker_root(APPLY) / PATH).read_bytes()
    assert b"<<<<<<< ours (src/)" in marked and b">>>>>>> theirs (new render)" in marked
    assert (tmp_path / PATH).read_bytes() == edited

    # A resolution under build/ is recorded by digest; it must keep the render's fences and blocks.
    resolutions = tmp_path / "build" / "resolutions"
    (resolutions / PATH).parent.mkdir(parents=True)
    (resolutions / PATH).write_bytes(new.replace(b"void g(int)\n", b"void g(int) /* port: real body */\n").replace(b"/* @socom-skeleton stub f__Fv */\n", b""))
    with pytest.raises(SocomError, match="fence lines differ"):
        _merge_scope(tmp_path, tracker, item, rendered, base, resolutions)
    resolved = new.replace(b"void g(int)\n", b"void g(int) /* port: real body */\n")
    (resolutions / PATH).write_bytes(resolved)
    rows, changes, _blobs = _merge_scope(tmp_path, tracker, item, rendered, base, resolutions)
    assert changes == {PATH: resolved} and rows[0]["merge"] == "resolved"
    assert rows[0]["resolution"] == {"path": f"build/resolutions/{PATH}", "sha256": sha(resolved)}
    # A resolution made before a later edit of src/ is stale: the conflict report must be current.
    (tmp_path / PATH).write_bytes(edited + b"// later\n")
    with pytest.raises(SocomError, match="conflict report is stale"):
        _merge_scope(tmp_path, tracker, item, rendered, base, resolutions)


# -- apply-check: the item's own write, later edits are drift ----------------------------------


def test_apply_check_verifies_the_recorded_write_and_reports_later_edits_as_drift(tmp_path: Path) -> None:
    edited = OLD.replace(b"void f()\n{\n}\n", b"void f()\n{\n\tport_init();\n}\n")
    new = _unit(("f__Fv", "void f()\n{\n}\n"), ("g__Fv", "void g()\n{\n}\n"), ("h__Fv", "void h()\n{\n}\n"))
    tracker, item, rendered, base = _setup(tmp_path, edited, new)
    rows, changes, blobs = _merge_scope(tmp_path, tracker, item, rendered, base, None)
    for data in blobs:
        put_blob(tmp_path, data)
    (tmp_path / PATH).write_bytes(changes[PATH])
    record = {"files": rows}
    assert verify_written(tmp_path, record, {PATH: new}) == ([], [])
    # A later edit (the port lane) is drift, not a failure.
    (tmp_path / PATH).write_bytes(changes[PATH] + b"// later port edit\n")
    assert verify_written(tmp_path, record, {PATH: new}) == ([], [PATH])
    # Changed stage 4 blocks fail: annotations change only through stage 4.
    (tmp_path / PATH).write_bytes(changes[PATH].replace(b".text socom:function:0x100000", b".text socom:function:0x100004"))
    problems, drift = verify_written(tmp_path, record, {PATH: new})
    assert drift == [PATH] and any("stage 4 blocks changed" in text for text in problems)
    # The inputs no longer render the recorded write: a failure.
    (tmp_path / PATH).write_bytes(changes[PATH])
    problems, _drift = verify_written(tmp_path, record, {PATH: OLD})
    assert problems == [f"{PATH}: a fresh render differs from the recorded write"]
    # A recorded merge that does not reproduce its write fails.
    forged = {"files": [{**rows[0], "after_sha256": sha(new)}]}
    (tmp_path / PATH).write_bytes(new)
    assert any("does not reproduce" in text for text in verify_written(tmp_path, forged, {PATH: new})[0])
    # A record from before merges wrote exactly its render: checked against the render only.
    plain = {"files": [{"path": PATH, "after_sha256": sha(new), "after_stage4_blocks_sha256": rows[0]["after_stage4_blocks_sha256"]}]}
    assert verify_written(tmp_path, plain, {PATH: new}) == ([], [])


