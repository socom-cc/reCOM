def test_cut_preamble_takes_whole_lines_and_merges_a_doubled_blank() -> None:
    text = '#include "a.h"\n\nint g;\n\nvoid f()\n{\n}\n\n// kept\nvoid g() {} // trailing\n\n'
    start = text.index("int g;")
    function = text.index("void f()")
    cuts = [(start, start + len("int g;")), (function, text.index("}\n") + 1)]
    assert cut_preamble(text, cuts) == '#include "a.h"\n\n// kept\nvoid g() {} // trailing\n'
    # Only blanks are dropped at the end; a text without cuts keeps every other byte.
    assert cut_preamble("a  \n\n\n", []) == "a  \n"
    assert cut_preamble("", []) == ""
    # A span sharing its line with other content takes only the span.
    shared = "int a; int b;\n"
    assert cut_preamble(shared, [(7, 13)]) == "int a; \n"


def test_parse_fences_reads_top_level_and_nested_entries() -> None:
    text = (
        "#include \"x.h\"\n\n"
        "/* @socom-skeleton stub Tick__4CFooFf */\nvoid CFoo::Tick(float)\n{\n"
        "\t/* @socom-skeleton stub count$12 */\n\tstatic int count;\n}\n\n"
        "/* @socom-skeleton body g_value */\nint g_value = 3;\n\n"
    )
    rows = parse_fences(text)
    assert [(row["kind"], row["name"]) for row in rows] == [("stub", "Tick__4CFooFf"), ("body", "g_value")]
    assert rows[0]["nested"] == [{"kind": "stub", "name": "count$12", "line": 6}]
    assert rows[1]["text"] == "int g_value = 3;"
    assert rows[0]["text"].endswith("}") and rows[0]["line"] == 3


def test_head_end_keeps_a_constructor_initializer_list() -> None:
    source = "CPnt3D::CPnt3D(float a) : x(a), y(0) { }\nbool CZ::Valid() const\n{ return true; }\n"
    scan = scan_text("src/x/p.cpp", source)
    first, second = [row for row in scan.definitions if row.in_class is None]
    text = source[first.start : first.end]
    assert text[_head_end(first.tokens, first.start) :] == " : x(a), y(0) { }"
    text = source[second.start : second.end]
    assert text[_head_end(second.tokens, second.start) :] == "\n{ return true; }"


def test_parameter_names_are_captured_and_respelled() -> None:
    source = "class CZ { public: void Set(int count, float (*scale)(int unused), const char *name); };\n"
    program = Program([scan_text("src/x/z.h", source)])
    scan = scan_text("src/x/z.cpp", "void CZ::Set(int count, float (*scale)(int unused), const char *) { }\n")
    definition = scan.definitions[0]
    parsed = function_symbol(program, definition.tokens, definition.scope, scan.tag)
    assert parsed.param_names == ["count", "scale", None]
    head, problems, _namespace = definition_text(program, parsed.symbol, "void", tag=scan.tag, names=parsed.param_names)
    assert not problems and head == "void CZ::Set(int count, float (*scale)(int), const char *)"
    assert definition_text(program, parsed.symbol, "void", tag=scan.tag)[0] == "void CZ::Set(int, float (*)(int), const char *)"


def test_operator_assignment_definitions_are_definitions() -> None:
    source = "struct CV { CV &operator=(const CV &o) { return *this; } };\nCV &CV::operator=(const char *) { return *this; }\n"
    program = Program([scan_text("src/x/v.cpp", source)])
    scan = scan_text("src/x/v.cpp", source)
    outer = [row for row in scan.definitions if row.in_class is None]
    inner = [row for row in scan.definitions if row.in_class is not None]
    assert len(outer) == 1 and len(inner) == 1
    assert mangle(function_symbol(program, outer[0].tokens, outer[0].scope, scan.tag).symbol) == "__as__2CVFPCc"


def test_top_level_const_makes_the_object_itself_const() -> None:
    pointer = {"t": "pointer", "to": {"t": "builtin", "code": "c"}}
    assert _top_level_const(pointer) == {"t": "pointer", "to": {"t": "builtin", "code": "c"}, "cv": "C"}
    array = {"t": "array", "size": 2, "of": {"t": "builtin", "code": "i"}}
    assert _top_level_const(array)["of"]["cv"] == "C"
    reference = {"t": "reference", "to": {"t": "named", "name": [{"name": "X"}]}}
    assert _top_level_const(reference) == reference


def test_split_blocks_keeps_the_leading_blocks_verbatim() -> None:
    text = BLOCK + "\n#include \"a.h\"\n"
    prefix, rest = split_blocks("src/a.cpp", text)
    assert prefix == BLOCK + "\n" and rest == '#include "a.h"\n'
    assert split_blocks("src/a.cpp", BLOCK) == (BLOCK, "")
    with pytest.raises(SocomError, match="not at the top"):
        split_blocks("src/a.cpp", "#include \"a.h\"\n" + BLOCK)


def test_read_source_keeps_one_newline_style(tmp_path: Path) -> None:
    crlf = tmp_path / "a.cpp"
    crlf.write_bytes(b"int a;\r\nint b;\r\n")
    assert read_source(crlf) == ("int a;\nint b;\n", "\r\n")
    mixed = tmp_path / "b.cpp"
    mixed.write_bytes(b"int a;\r\nint b;\n")
    with pytest.raises(SocomError, match="mixes newline styles"):
        read_source(mixed)
    assert read_source(tmp_path / "missing.cpp") == ("", "\r\n")


def _rows(names: list[str]) -> list[dict]:
    return [{"artifact": name, "name": name, "position": index} for index, name in enumerate(names, start=1)]


def test_entry_order_interleaves_data_with_the_owners_of_local_statics() -> None:
    chain = _rows(["f1", "f2", "f3"])
    order_of = {row["artifact"]: row["position"] for row in chain}
    data = [{"region": 21, "rows": _rows(["g1", "s_in_f2", "g2"])}]
    owners = {"s_in_f2": "f2"}
    order = _entry_order(chain, order_of, data, [21], owners, set(), relax=False)
    assert order == [("d", "g1"), ("f", "f1"), ("f", "f2"), ("d", "g2"), ("f", "f3")]
    # A local static whose owner contradicts the data order makes a cycle; relaxed, the pins constrain nothing.
    data = [{"region": 21, "rows": _rows(["s_in_f3", "s_in_f1"])}]
    owners = {"s_in_f3": "f3", "s_in_f1": "f1"}
    assert _entry_order(chain, order_of, data, [21], owners, set(), relax=False) is None
    assert _entry_order(chain, order_of, data, [21], owners, set(), relax=True) == [("f", "f1"), ("f", "f2"), ("f", "f3")]


def test_preview_root_is_a_build_directory_only(tmp_path: Path) -> None:
    (tmp_path / "build").mkdir()
    (tmp_path / "src").mkdir()
    for value in ("src/preview", "build", "elsewhere"):
        with pytest.raises(SocomError):
            preview_root(tmp_path, value)
    assert preview_root(tmp_path, "build/preview") == (tmp_path / "build" / "preview").resolve()
    occupied = tmp_path / "build" / "occupied"
    occupied.mkdir()
    (occupied / "notes.txt").write_text("x", encoding="utf-8")
    with pytest.raises(SocomError, match="not empty"):
        preview_root(tmp_path, "build/occupied")
    (occupied / "skeleton-write.json").write_text(json.dumps({"kind": WRITE_KIND}), encoding="utf-8")
    assert preview_root(tmp_path, "build/occupied") == occupied.resolve()


