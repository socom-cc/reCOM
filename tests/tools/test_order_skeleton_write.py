@needs_inputs
def test_every_planned_row_is_written_once_or_listed(rendered: dict) -> None:
    from tools._socom.source_apply import parse_blocks

    inputs, manifest, files = rendered["inputs"], rendered["first"]["manifest"], rendered["first"]["files"]
    waiting = {row.get("artifact") for row in manifest["waiting"]}
    # Local statics of moved bodies are the bodies' own text (no fence of their own).
    in_bodies = {inner["artifact"] for row in manifest["entries"] if row.get("fence") == "body" for inner in row.get("nested") or []}
    for _number, unit in inputs.units:
        text = files[unit["workspace_path"]].decode("utf-8").replace("\r\n", "\n")
        _bom, blocks, rest = parse_blocks(text)
        source = (inputs.root / unit["workspace_path"]).read_bytes().decode("utf-8").replace("\r\n", "\n")
        assert blocks == parse_blocks(source)[1], unit["unit"]
        names = Counter(row["name"] for row in parse_fences(rest))
        names.update(inner["name"] for row in parse_fences(rest) for inner in row["nested"])
        for row in unit["functions"]:
            if not row.get("in_class"):
                assert names[row["name"]] == 1, (unit["unit"], row["name"])
        for region in unit["data"]:
            for row in region["rows"]:
                if row["artifact"] in waiting or row["artifact"] in in_bodies:
                    continue
                assert names[row["name"]] == 1, (unit["unit"], row["name"])
        assert "0x" not in "".join(line for line in rest.split("\n") if "@socom-skeleton" in line)


@needs_inputs
def test_bodies_land_once_and_judgment_rows_all_get_a_default(rendered: dict) -> None:
    inputs, manifest = rendered["inputs"], rendered["first"]["manifest"]
    sources = Counter(row["source"] for row in manifest["entries"] if row.get("fence") == "body" or row["kind"] == "held-function")
    snapshot = {row["id"] for row in inputs.snapshot["bodies"]}
    assert {identity for identity in sources if identity in snapshot} == snapshot
    assert all(sources[identity] == 1 for identity in snapshot)
    assert len(manifest["judgment"]) == len(inputs.manifest["judgment"])
    assert all(row["default"] and row["flag"] and isinstance(row["waits"], bool) for row in manifest["judgment"])
    orphans = [path for path, row in inputs.files.items() if row["orphan"]]
    assert sorted(row["path"] for row in manifest["deleted"]) == sorted(orphans)
    assert all(rendered["first"]["files"][path] is None for path in orphans)
    holding = [row["path"] for row in manifest["files"] if row["action"] == "holding"]
    assert holding and all(path.endswith("_holding.cpp") for path in holding)


@needs_inputs
def test_the_cli_writes_a_preview_that_checks(root: Path) -> None:
    preview = root / "build" / "test-skeleton-preview"
    if preview.exists():
        shutil.rmtree(preview)
    try:
        for command in (["write", "--segment", "1"], ["check"]):
            completed = subprocess.run(
                [sys.executable, "tools/socom.py", "order", "skeleton", *command, "--root", "build/test-skeleton-preview"],
                cwd=root, text=True, encoding="utf-8", capture_output=True, check=False,
            )
            report = json.loads(completed.stdout)
            assert completed.returncode == 0, report
        assert report["ok"] and not report["failed"]
        assert report["s1"]["failed"] == 0 and report["s4"]["bodies_checked"] > 0
        refused = subprocess.run(
            [sys.executable, "tools/socom.py", "order", "skeleton", "write", "--all", "--root", "src/preview"],
            cwd=root, text=True, encoding="utf-8", capture_output=True, check=False,
        )
        assert refused.returncode != 0 and "preview directory under build/" in refused.stdout + refused.stderr
    finally:
        if preview.exists():
            shutil.rmtree(preview)
