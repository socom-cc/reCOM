def test_stage_4_custody_counts_an_accepted_skeleton_write_as_its_stage_4_content(tmp_path: Path, tracker: dict) -> None:
    from tools._socom.source_apply import content_sha256
    from tools._socom.source_gate import _applied_files

    before = (BLOCK + "\nint a;\n").encode()
    after = (BLOCK + "\nint a;\n\n/* @socom-skeleton stub f__Fv */\nvoid f()\n{\n}\n").encode()
    path = "src/gamez/zAI/zai.h"
    (tmp_path / path).parent.mkdir(parents=True)
    (tmp_path / path).write_bytes(after.replace(b"\n", b"\r\n"))  # a CRLF checkout of the same content
    updated = _applied(tracker)
    prepare = _item(updated, ORDER_SKELETON_PREPARE_ID)
    sha = hashlib.sha256(before).hexdigest()
    row = {"path": path, "action": "header", "before_sha256": sha, "before_content_sha256": content_sha256(before),
           "stage4_blocks_sha256": blocks_sha256(before), "after_sha256": hashlib.sha256(after).hexdigest(),
           "after_stage4_blocks_sha256": blocks_sha256(after)}
    record_skeleton(prepare, _record(ORDER_SKELETON_PREPARE_ID, [row]), "2026-11-01T00:00:00Z")
    stage4 = next(item for item in updated["work_items"] if item.get("kind") == "source-apply-segment")
    stage4["source_apply"] = {"files": [{"path": path, "sha256": sha, "content_sha256": content_sha256(before)}]}
    # Not accepted yet: no custody, and stage 4 sees the changed file.
    assert skeleton_custody(tmp_path, updated) == {}
    assert dict((row[0], row[1]) for row in _applied_files(tmp_path, updated))[path] != sha
    prepare["status"] = "accepted"
    assert skeleton_custody(tmp_path, updated)[path]["before_sha256"] == sha
    assert dict((row[0], row[1]) for row in _applied_files(tmp_path, updated))[path] == sha
    # A shared file whose record predates another plan's block: its authored content is what stage 4 recorded.
    stage4["source_apply"]["files"][0]["sha256"] = "0" * 64
    assert dict((row[0], row[1]) for row in _applied_files(tmp_path, updated))[path] == sha
    # A later stage 4 write is refused until the skeleton item is reopened.
    with pytest.raises(SocomError, match="reopen those items first"):
        refuse_stage4_writes(updated, [path])
    prepare["status"] = "ready"
    refuse_stage4_writes(updated, [path])
    # Changed stage 4 blocks break the custody.
    prepare["status"] = "accepted"
    (tmp_path / path).write_bytes(after.replace(b"defines main", b"defines other"))
    assert skeleton_custody(tmp_path, updated) == {}


def test_stage_4_retires_the_orphans_an_accepted_or_reopened_skeleton_item_deleted() -> None:
    gone = {"path": "src/gamez/zAI/zai_old.cpp", "action": "orphan-deleted", "before_sha256": "a" * 64, "after_sha256": None}
    # A merge re-apply finds the orphan deleted already: no before, the frozen base's digest kept.
    merged = {"path": "src/gamez/zAI/zai_older.cpp", "action": "orphan-deleted", "before_sha256": None, "base_sha256": "b" * 64,
              "after_sha256": None}
    written = {"path": "src/gamez/zAI/zai.h", "action": "header", "before_sha256": "c" * 64, "after_sha256": "d" * 64}
    item = {"id": ORDER_SKELETON_PREPARE_ID, "kind": ORDER_PREPARE_KIND, "status": "accepted",
            "order_skeleton": _record(ORDER_SKELETON_PREPARE_ID, [gone, merged, written])}
    stage: dict = {"name": "authored-function-order"}
    tracker = {"work_items": [item], "stages": [stage]}
    retired = [{"path": gone["path"], "sha256": "a" * 64, "bytes": None, "by": ORDER_SKELETON_PREPARE_ID},
               {"path": merged["path"], "sha256": "b" * 64, "bytes": None, "by": ORDER_SKELETON_PREPARE_ID}]
    assert skeleton_deletions(tracker) == retired
    # Never reviewed, under review or rejected: its deletions are not stage 4's.
    for status in ("blocked", "ready", "in_progress", "awaiting_acceptance"):
        item["status"] = status
        assert skeleton_deletions(tracker) == [], status
    # Sent back by a reopening for a stage 4 amendment: it keeps its record until the re-apply replaces it, and the
    # files stay deleted meanwhile (held, then re-planned once the reopening is absorbed).
    reopening = {"id": "socom:order-reopening:001", "status": "open", "items": [ORDER_SKELETON_PREPARE_ID]}
    stage["reopenings"] = [reopening]
    for state, status in (("open", "blocked"), ("absorbed", "ready"), ("absorbed", "in_progress")):
        reopening["status"], item["status"] = state, status
        assert skeleton_deletions(tracker) == retired, (state, status)
    # A reopening of other items leaves this one's deletions out.
    reopening["items"] = ["socom:work:order-segment-001-apply"]
    assert skeleton_deletions(tracker) == []
    # Without a record nothing is retired.
    reopening["items"] = [ORDER_SKELETON_PREPARE_ID]
    item.pop("order_skeleton")
    assert skeleton_deletions(tracker) == []


def test_a_deleted_orphan_path_stage_4_creates_again_is_its_new_file_not_retired(tmp_path: Path) -> None:
    from tools._socom.order_skeleton_merge import put_blob
    from tools._socom.order_skeleton_route import (
        BASE_DIR, ROUTE_DIR, _sha, current_rows, deleted_content, recreated_paths, skeleton_written,
    )

    old = b"// provisional\nint old;\n"
    gone = {"path": "src/gamez/zAI/ai_main.cpp", "action": "orphan-deleted", "before_sha256": _sha(old), "after_sha256": None}
    other = {"path": "src/gamez/zAI/zai_old.cpp", "action": "orphan-deleted", "before_sha256": "a" * 64, "after_sha256": None}
    item = {"id": ORDER_SKELETON_PREPARE_ID, "kind": ORDER_PREPARE_KIND, "status": "accepted",
            "order_skeleton": _record(ORDER_SKELETON_PREPARE_ID, [gone, other])}
    stage4 = {"id": "socom:work:source-segment-014-apply", "kind": "source-apply-segment",
              "source_apply": {"created": [], "moves": [], "files": []}}
    tracker = {"work_items": [item, stage4], "stages": [{"name": "authored-function-order"}]}
    assert [row["path"] for row in skeleton_deletions(tracker)] == [gone["path"], other["path"]]
    assert recreated_paths(tracker) == {} and set(skeleton_written(tracker)) == {gone["path"], other["path"]}
    # A stage 4 amendment creates a new unit file at the deleted path: stage 4's file, the deletion only history.
    stage4["source_apply"]["created"] = [gone["path"]]
    assert [row["path"] for row in skeleton_deletions(tracker)] == [other["path"]]
    assert recreated_paths(tracker) == {gone["path"]: {"path": gone["path"], "sha256": _sha(old), "by": ORDER_SKELETON_PREPARE_ID}}
    created = {gone["path"]}
    assert current_rows(item["order_skeleton"], created) == [other] and set(skeleton_written(tracker)) == {other["path"]}
    refuse_stage4_writes(tracker, [gone["path"]])
    with pytest.raises(SocomError, match="reopen those items first"):
        refuse_stage4_writes(tracker, [other["path"]])
    # The re-apply's record no longer lists the path: its earlier record in the review history keeps it recreated.
    item["review_history"] = [{"order_skeleton": item["order_skeleton"]}]
    item["order_skeleton"] = _record(ORDER_SKELETON_PREPARE_ID, [other])
    assert list(recreated_paths(tracker)) == [gone["path"]]
    # The deleted content: the frozen base copy, an earlier base under base-history once a rebase advanced it, the blobs.
    assert deleted_content(tmp_path, gone["path"], _sha(old)) is None
