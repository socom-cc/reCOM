def test_adding_the_prepare_keeps_the_plans_and_narrows_the_applies(tracker: dict) -> None:
    before = copy.deepcopy(tracker)
    updated = _prepared(tracker)
    assert audit_tracker(updated, strict=True) == []
    prepare = _item(updated, ORDER_SKELETON_PREPARE_ID)
    plans = sorted(row["id"] for row in updated["work_items"] if row.get("kind") == "order-plan-segment")
    assert prepare["dependencies"] == [ORDER_SKELETON_ROUTE_ID, "socom:work:order-link", *plans]
    assert prepare["status"] == "ready" and prepare["resources"] == prepare["batch"]["files"]
    # The plan items and their acceptances are byte for byte the same.
    for kind in ("order-plan-segment", "order-plan-link"):
        assert [row for row in updated["work_items"] if row.get("kind") == kind] == \
            [row for row in before["work_items"] if row.get("kind") == kind]
    for row in _applies(updated):
        assert row["dependencies"][-1] == ORDER_SKELETON_PREPARE_ID and row["status"] == "blocked"
        assert row["resources"] == row["batch"]["files"] and row["batch"]["directories"] == _item(before, row["id"])["batch"]["directories"]
    record = next(row for row in updated["stages"] if row["name"] == "authored-function-order")["decomposition"]["skeleton_prepare"]
    assert record["item"] == ORDER_SKELETON_PREPARE_ID and len(record["resources_sha256"]) == 64
    # The audit binds the reservations: a widened apply is refused.
    tampered = copy.deepcopy(updated)
    _applies(tampered)[0]["resources"].append("src/gamez/zAI/other.cpp")
    assert any("must reserve exactly its units' files" in error for error in audit_tracker(tampered))


