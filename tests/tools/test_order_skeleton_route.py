def _applies(tracker: dict) -> list[dict]:
    return [row for row in tracker["work_items"] if row.get("kind") == ORDER_APPLY_KIND]


def _unit_files(tracker: dict) -> dict[str, list[str]]:
    rows = {}
    for row in _applies(tracker):
        directory = row["batch"]["directories"][0]
        rows[row["id"]] = sorted({f"{directory}/{unit}" for unit in row["batch"]["units"]}, key=str.casefold)
    return rows


def _prepared(tracker: dict, *, gate: bool = True) -> dict:
    """A copy with the skeleton route gate opened and the prepare item added (as the route's commands do)."""

    updated = copy.deepcopy(tracker)
    if gate:
        registered = set((capability_opening(ORDER_SKELETON_ROUTE_ID) or {}).get("commands") or [])
        open_capability_gate(updated, ORDER_SKELETON_ROUTE_ID, registered)
        refresh_ready_and_stages(updated)
    add_skeleton_prepare(updated, prepare_files=["src/gamez/zAI/zai.h", "src/gamez/zAI/zai_holding.cpp"],
                         unit_files=_unit_files(tracker), manifest_sha256="m" * 64, write_sha256="w" * 64, counts={"header": 1})
    refresh_ready_and_stages(updated)
    updated["revision"] += 1
    return updated


def _item(tracker: dict, item_id: str) -> dict:
    return next(row for row in tracker["work_items"] if row["id"] == item_id)


