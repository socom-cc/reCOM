def _record(item_id: str, files: list[dict] | None = None) -> dict:
    rows = files or [{"path": "src/gamez/zAI/zai.h", "action": "header", "before_sha256": "a" * 64, "before_content_sha256": "c" * 64,
                      "stage4_blocks_sha256": "d" * 64, "after_sha256": "b" * 64, "after_stage4_blocks_sha256": "d" * 64}]
    from tools._socom.order_skeleton_route import _digest

    return {"kind": RECORD_KIND, "schema_version": 1, "item": item_id, "applied_by": "worker", "files": rows,
            "files_sha256": _digest(rows), "inputs": {"manifest_sha256": "m" * 64, "snapshot_sha256": "s" * 64, "base_tree_sha256": "t" * 64,
                                                      "stage4_baseline_sha256": "4" * 64},
            "write_sha256": "w" * 64, "known_conflicts": [], "waiting": [], "waiting_by_kind": {}, "flags": {}, "decisions": None}


def _applied(tracker: dict) -> dict:
    updated = _prepared(tracker)
    prepare = _item(updated, ORDER_SKELETON_PREPARE_ID)
    prepare.update(status="in_progress", lease={"owner": "worker", "claimed_at": "2026-11-01T00:00:00Z",
                                                "heartbeat_at": "2026-11-01T00:00:00Z", "expires_at": "2999-01-01T00:00:00Z"})
    record_skeleton(prepare, _record(ORDER_SKELETON_PREPARE_ID), "2026-11-01T00:00:00Z")
    return updated


def _ok(tracker: dict, item_id: str) -> dict:
    return {"ok": True, "record_sha256": record_sha256(_item(tracker, item_id)["order_skeleton"]), "problems": []}


def test_handoff_and_acceptance_need_the_record_and_an_independent_verifier(tracker: dict) -> None:
    from tools._socom.tracker import work_packet

    updated = _applied(tracker)
    packet = work_packet(updated, ORDER_SKELETON_PREPARE_ID, "worker")
    assert packet["role"] == "socom-source-worker" and packet["allowed_paths"][:2] == ["src/gamez/zAI/zai.h", "src/gamez/zAI/zai_holding.cpp"]
    assert "progress handoff-order-skeleton" in packet["handoff"] and any("accept-order-skeleton" in line for line in packet["validation"])
    with pytest.raises(SocomError, match="apply-check fails"):
        handoff_skeleton(updated, ORDER_SKELETON_PREPARE_ID, "worker", "done", [], {"ok": False, "problems": ["x"]})
    handoff_skeleton(updated, ORDER_SKELETON_PREPARE_ID, "worker", "done", [], _ok(updated, ORDER_SKELETON_PREPARE_ID))
    prepare = _item(updated, ORDER_SKELETON_PREPARE_ID)
    assert prepare["status"] == "awaiting_acceptance" and prepare["handoff"]["route"] == HANDOFF_ROUTE
    assert f"{RECORD_CITATION}{record_sha256(prepare['order_skeleton'])}" in prepare["evidence"]
    assert any(text.startswith("order-skeleton-file src/gamez/zAI/zai.h before:") for text in prepare["evidence"])
    for name, match in (("worker", "independent socom-verifier"), ("socom-tool-maintainer-1", "tool maintainer")):
        with pytest.raises(SocomError, match=match):
            accept_skeleton(updated, ORDER_SKELETON_PREPARE_ID, name, ["review"], _ok(updated, ORDER_SKELETON_PREPARE_ID))
    changed = copy.deepcopy(updated)
    _item(changed, ORDER_SKELETON_PREPARE_ID)["order_skeleton"]["write_sha256"] = "x" * 64
    with pytest.raises(SocomError, match="record changed since its handoff"):
        accept_skeleton(changed, ORDER_SKELETON_PREPARE_ID, "verifier", ["review"], _ok(changed, ORDER_SKELETON_PREPARE_ID))
    accept_skeleton(updated, ORDER_SKELETON_PREPARE_ID, "verifier", ["apply-check passes"], _ok(updated, ORDER_SKELETON_PREPARE_ID))
    refresh_ready_and_stages(updated)
    assert prepare["accepted"]["route"] == ACCEPT_ROUTE and audit_skeleton_records(updated) == []
    assert all(row["status"] == "ready" for row in _applies(updated))
    assert audit_tracker(updated) == []
    forged = copy.deepcopy(updated)
    _item(forged, ORDER_SKELETON_PREPARE_ID)["accepted"].pop("route")
    assert any("must be accepted by progress accept-order-skeleton" in error for error in audit_skeleton_records(forged))


def test_a_reopened_skeleton_item_keeps_its_record_and_the_re_apply_replaces_it(tracker: dict) -> None:
    updated = _applied(tracker)
    handoff_skeleton(updated, ORDER_SKELETON_PREPARE_ID, "worker", "done", [], _ok(updated, ORDER_SKELETON_PREPARE_ID))
    accept_skeleton(updated, ORDER_SKELETON_PREPARE_ID, "verifier", ["review"], _ok(updated, ORDER_SKELETON_PREPARE_ID))
    refresh_ready_and_stages(updated)
    first = _applies(updated)[0]
    first.update(status="accepted", handoff={"owner": "worker-2", "route": HANDOFF_ROUTE}, accepted={"by": "verifier", "route": ACCEPT_ROUTE})
    first["order_skeleton"] = _record(first["id"], [{"path": first["resources"][0], "action": "unit", "before_sha256": "a" * 64,
                                                      "before_content_sha256": "c" * 64, "stage4_blocks_sha256": "d" * 64,
                                                      "after_sha256": "e" * 64, "after_stage4_blocks_sha256": "d" * 64}])
    first["evidence"] = [f"{RECORD_CITATION}{record_sha256(first['order_skeleton'])}"]
    with pytest.raises(SocomError, match="handoff owner"):
        reopen_work(updated, ORDER_SKELETON_PREPARE_ID, "worker", "re-plan", ["evidence"])
    reopen_work(updated, ORDER_SKELETON_PREPARE_ID, "verifier", "a header decision changes", ["evidence"])
    refresh_ready_and_stages(updated)
    prepare = _item(updated, ORDER_SKELETON_PREPARE_ID)
    assert prepare["status"] == "ready" and prepare["order_skeleton"]["item"] == ORDER_SKELETON_PREPARE_ID
    assert prepare["review_history"][-1]["reopened_by"] == "verifier" and prepare["review_history"][-1]["order_skeleton"]
    assert not any(text.startswith(RECORD_CITATION) for text in prepare["evidence"])
    # Accepted applies keep their acceptance; the others wait for the prepare again.
    assert first["status"] == "accepted" and all(row["status"] == "blocked" for row in _applies(updated)[1:])
    assert audit_tracker(updated) == []
    # The re-apply replaces the record and keeps the old one in the review history.
    old = copy.deepcopy(prepare["order_skeleton"])
    renewed = {**_record(ORDER_SKELETON_PREPARE_ID), "write_sha256": "v" * 64}
    record_skeleton(prepare, renewed, "2026-11-02T00:00:00Z")
    assert prepare["order_skeleton"]["write_sha256"] == "v" * 64
    assert prepare["review_history"][-1]["order_skeleton"]["write_sha256"] == old["write_sha256"]


